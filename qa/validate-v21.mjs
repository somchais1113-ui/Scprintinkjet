import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { execFileSync } from 'node:child_process';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const ctx={window:{}};vm.runInNewContext(read('data/site-data.js'),ctx);
const s=ctx.window.PROCLEANING_SITE;
if(![1,2].includes(s.schemaVersion))throw Error('Invalid data schemaVersion');
for(const name of ['services','pricing','team','features','testimonials','blogs'])if(!Array.isArray(s[name]))throw Error('Invalid list '+name);
for(const name of ['brand','navigation','hero','headings','labels','footer','contact','settings','design','photos'])if(typeof s[name]!=='object')throw Error('Missing '+name);
for(const name of ['primary','ink','body','border','footer'])if(!/^#[0-9a-f]{6}$/i.test(s.design[name]))throw Error('Invalid color '+name);
const html=read('index.html');
for(const file of ['data/site-data.js','src/scripts/site-runtime.js','src/styles/06-editor-overrides.css'])if(!html.includes(file))throw Error('Missing file reference '+file);
for(const file of ['tools/site-manager.html','tools/site-manager.js','tools/site-manager.css','tools/zip-store.js','docs/08-CONTENT-WORKFLOW.md'])if(!fs.existsSync(path.join(root,file)))throw Error('Missing required file '+file);
for(const f of ['src/scripts/site-runtime.js','src/scripts/main.js','src/scripts/ui.js','tools/site-manager.js','tools/zip-store.js','data/site-data.js'])execFileSync('node',['--check',path.join(root,f)]);
const manifest=JSON.parse(read('assets/images/manifest.json'));
if(manifest.images.length!==18)throw Error('Expected 18 WebP image slots');
for(const slot of manifest.images)if(!fs.existsSync(path.join(root,slot.path)))throw Error('Missing '+slot.path);
console.log(`V2.1 PASS: data schema, 18 image slots, editor files, HTML dependencies, and JS syntax`);
