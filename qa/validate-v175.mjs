import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const read=name=>fs.readFileSync(new URL('../'+name,import.meta.url),'utf8');
const {window}=vm.runInNewContext(read('data/pricing-demo-data.js')+';({window})',{window:{}});
const catalog=window.SCWORK_PRICING_DEMO;
const b=require('../src/scripts/rate-card-builder.js'),m=require('../src/scripts/pricing-master.js'),engine=require('../src/scripts/pricing-engine.js');
const fresh=m.fresh(catalog,b);
const stamp='2026-01-01T00:00:00Z';
const card=s=>m.makeCard(s,catalog,b,stamp);
assert.throws(()=>card(fresh),/SELECT_MATERIAL/);
const before=structuredClone(fresh);
before.selected=['pp-white','paper-sticker'];
before.vatPct=0;
before.globalRates={electricity:4,fuel:34,freight:100};
Object.assign(before.rules['pp-white'],{materialCost:10,printCost:5,finishingCost:1,wastePct:10,setupCost:20,kwhPerUnit:.5,litresPerJob:.2,freightTripsPerJob:.1});
Object.assign(before.rules['paper-sticker'],{materialCost:8,printCost:5,finishingCost:1});
const rateBefore=card(before);
const after=structuredClone(before);after.globalRates={electricity:5,fuel:40,freight:130};
const rateAfter=card(after);
assert.equal(rateAfter.categories[0].materials.length,2);
const specs=(id,n)=>({categoryId:'sticker',materialId:id,widthCm:5,heightCm:5,quantity:n,desiredPieces:n,addonIds:[]});
const q=(id,n,c)=>engine.calculate(specs(id,n),c);
assert(q('pp-white',500,rateAfter).total>q('pp-white',500,rateBefore).total);
assert.equal(q('paper-sticker',500,rateAfter).total,q('paper-sticker',500,rateBefore).total);
assert.equal(m.effectiveRule(after.rules['pp-white'],after.globalRates,b).variable,2.5);
assert.equal(m.effectiveRule(after.rules['pp-white'],after.globalRates,b).fixed,21);
const serialized=JSON.stringify(rateAfter);
for(const key of [...m.rateKeys,...m.usageKeys,'reason','globalRates','marginPct','supplierFee','addonCosts','setupCost','overhead','materialCost','printCost','history'])assert(!serialized.includes('"'+key+'"'),key+' leaked');
const selected=structuredClone(after);selected.selected=['pp-white'];selected.rules['pp-white'].addonCosts.lamination=3;
const final=card(selected);
assert.deepEqual(Array.from(final.categories[0].materials,x=>x.id),['pp-white']);
assert.deepEqual(Array.from(final.categories[0].materials[0].addons,x=>x.id),['lamination']);
assert.equal(final.categories[0].materials[0].pricingMode,'tier_floor');
for(const material of rateAfter.categories[0].materials){
 const ts=material.tiers;
 for(const {min} of ts.slice(1))assert(q(material.id,(min-1)*40,rateAfter).total<=q(material.id,min*40,rateAfter).total);
}
const synthetic=[{min:10,max:49,price:45},{min:50,max:null,price:35}];
assert.equal(engine.tierSubtotal(synthetic,49,'tier_floor'),2205);
assert.equal(engine.tierSubtotal(synthetic,50,'tier_floor'),2205);
assert.equal(engine.tierSubtotal(synthetic,64,'tier_floor'),2240);
assert.equal(engine.tierSubtotal(synthetic,50),1750);
const old=m.normalize({schemaVersion:1,version:'OLD',vatPct:7,rules:before.rules},catalog,b);
assert.equal(old.schemaVersion,2);assert.equal(old.globalRates.fuel,0);assert(old.selected.includes('pp-white'));
assert.equal(m.normalize(JSON.parse(JSON.stringify(after)),catalog,b).rules['pp-white'].kwhPerUnit,.5);
const incomplete=structuredClone(after);incomplete.globalRates.fuel=null;assert.throws(()=>card(incomplete),/INCOMPLETE_SHARED_RATES/);
const invalid=structuredClone(after);invalid.rules['pp-white'].addonCosts.lamination=-1;
assert.throws(()=>card(invalid),/BAD_ADDON/);
const vatBlank=structuredClone(after);vatBlank.vatPct=null;assert.throws(()=>card(vatBlank),/BAD_VAT/);
const thin=structuredClone(after);thin.selected=['pp-white'];Object.assign(thin.rules['pp-white'],{materialCost:0,printCost:0,finishingCost:0});
assert(card(thin).categories[0].materials[0].tiers[0].price>0);
assert.match(read('data/pricing-public-data.js'),/SCWORK_PRICING_PUBLIC = null/);
console.log('PASS V1.7.5 shared cost propagation, selective export, partial add-ons, protected public data, legacy import, no falling totals, validation.');
