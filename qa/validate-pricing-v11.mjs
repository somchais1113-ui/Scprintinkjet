import assert from 'node:assert/strict';
import { readFileSync,existsSync } from 'node:fs';
import { resolve,dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(resolve(root,p),'utf8');
const ctx={window:{}};
vm.runInNewContext(read('data/pricing-demo-data.js'),ctx);
const pricing=ctx.window.SCWORK_PRICING_DEMO;
assert(pricing.demonstrationOnly,'Reference table should be clearly demo-only');
const {calculate}=await import('../src/scripts/pricing-engine.js');
const base={categoryId:'sticker',materialId:'paper-sticker',widthCm:5,heightCm:5,desiredPieces:500,addonIds:[]};
const result=calculate(base,pricing);
assert.equal(result.details.piecesPerSheet,40);
assert.equal(result.units,13);
assert.equal(result.basePrint,455);
assert.equal(result.vat,31.85);
assert.equal(result.total,486.85);
const plus=calculate({...base,addonIds:['lamination','design']},pricing);
assert.equal(plus.addonsTotal,730);
assert.equal(plus.total,1267.95);
assert.throws(()=>calculate({...base,widthCm:90},pricing),/TOO_LARGE_FOR_A3/);
const sqm=calculate({categoryId:'sticker',materialId:'pvc-sqm',areaWidthCm:100,areaHeightCm:100,quantity:2,addonIds:[]},pricing);
assert.equal(sqm.total,406.6);
const tier=calculate({categoryId:'print',materialId:'business-card',quantity:100,addonIds:[]},pricing);
assert.equal(tier.basePrint,99);
const preset=calculate({categoryId:'acrylic',materialId:'acrylic-keychain',quantity:50,presetId:'3x3',addonIds:[]},pricing);
assert.equal(preset.basePrint,950);
const siteContext={window:{}};
vm.runInNewContext(read('data/site-data.js'),siteContext);
const site=siteContext.window.PROCLEANING_SITE;
assert.equal(site.commerce.processSteps.length,4);
assert.equal(site.i18n.th.commerce.processSteps.length,4);
assert(read('src/scripts/i18n.js').includes("'commerce'"));
const home=read('index.html');
for(const token of ['topContactBar','data-language-launcher','scProcessSteps','scPriceLink','pricing-calculator.html'])assert(home.includes(token),token+' missing');
const rfq=read('src/scripts/rfq-demo.js');
assert(rfq.includes('scwork-pricing-handoff'),'Estimator handoff missing');
for(const script of ['src/scripts/pricing-calculator.js','src/scripts/pricing-engine.js','src/scripts/commerce-enhancements.js','data/pricing-demo-data.js'])assert(existsSync(resolve(root,script)),script+' missing');
console.log('SCWORK pricing QA PASS: calculations, add-ons, tiers, unsupported sizes, localization, page links and RFQ handoff');
