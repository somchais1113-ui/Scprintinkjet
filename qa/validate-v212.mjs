import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const home=read('index.html');
const services=home.indexOf('id="services"');
const price=home.indexOf('id="pricing"');
const process=home.indexOf('id="how-it-works"');
assert(services>=0 && services<price && price<process);
assert.equal(home.match(/id="pricing"/g)?.length,1);
assert.match(home, /<\/section>\s*<section class="section pricing-section" id="pricing"/);
assert.doesNotMatch(home,/v24-rfq-band|quote-section|id="quote-entry-title"|id="quote-title"|id="quote(?:Main|Small)Image"/);
assert.match(home,/id="scPriceLink"[^>]*href="\.\/smart-quote\.html"/);
assert.match(home,/id="pricingGrid"/);
const ui=read('src/scripts/ui.js');
assert.match(ui,/price-card--sticker/);
assert.match(ui,/price-card__features/);
assert.match(ui,/href="\.\/smart-quote\.html\?category=/);
const css=read('src/styles/19-social-proof-footer.css');
assert.match(css,/#pricing \.price-card--sticker \.price-card__features\{font-size:clamp\(18px,1\.65vw,21px\);line-height:1\.6;gap:14px\}/);
assert.match(home,/19-social-proof-footer\.css\?v=2\.1\.[234]/);
console.log('PASS V2.1.2: home placement, duplicate quote sections removed, larger card copy, quote links preserved.');
