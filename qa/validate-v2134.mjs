import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(join(root,p),'utf8');
const page=read('about.html'),home=read('index.html'),js=read('src/scripts/about-page.js'),motion=read('src/styles/34-cinematic-hero.css');
for(const label of ['About us','Who We Are','Our Philosophy','Good Design Must Work.','Our Expertise','Design Solutions','Printing &amp; Production Solutions','Technology &amp; Process Development','Our Approach','We Think.','We Design.','We Make It Work.','Our Commitment','Ritthee Kolakij Co., Ltd.'])assert(page.includes(label),label);
const nav=home.match(/<nav class="main-nav"[\s\S]*?<\/nav>/)[0];
assert(nav.indexOf('data-sc-about-link')>nav.indexOf('href="#blog"')&&nav.indexOf('data-sc-about-link')<nav.indexOf('href="#contact"'));
assert(home.includes('id="clientCreditsNav"')&&home.includes('id="about"'));
assert.equal((page.match(/data-hero-slide="/g)||[]).length,3);
assert.equal((page.match(/data-hero-dot="/g)||[]).length,3);
assert(page.includes('34-cinematic-hero.css')&&js.includes('duration=7400')&&js.includes('photoFadeDuration=880'));
assert(motion.includes('880ms cubic-bezier(.35,.05,.22,1)')&&motion.includes('9s linear both')&&motion.includes('scale(1.075)'));
for(const m of page.matchAll(/(?:src|href)="\.\/([^"#?]+)(?:[?#][^"]*)?"/g))assert(existsSync(join(root,m[1])),m[1]);
for(const s of ['about.html','about-page','43-about-v2133','34-cinematic-hero'])assert(read('qa/build-public-v2133.mjs').includes("'"+s+"'"));
assert(!read('qa/build-public-v2133.mjs').includes("'admin-cloud'"));
assert.equal(JSON.parse(read('package.json')).version,'2.1.34');
console.log('V2.1.34 PASS: About us, navigation, motion parity, image assets and public build boundary');
